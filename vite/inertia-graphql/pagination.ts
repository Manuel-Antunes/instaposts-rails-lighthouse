import {
  type FieldNode,
  type FragmentDefinitionNode,
  type GraphQLField,
  type GraphQLNamedType,
  type GraphQLSchema,
  getNamedType,
  isInterfaceType,
  isObjectType,
  type OperationDefinitionNode,
  parse,
  type SelectionSetNode,
} from 'graphql'

// How Lighthouse paginates a field: @paginate / @hasMany(type: ...) rewrite it into
// one of these shapes, with these arguments.
export type PaginationType = 'CONNECTION' | 'PAGINATOR' | 'SIMPLE'

export type PaginatedField = {
  type: PaginationType
  // The argument that moves to another page: after (cursor) or page (number).
  pageArgument: 'after' | 'page'
  // The field's other arguments: what tells one list from another in the cache.
  keyArgs: string[]
}

export type OperationPagination = { path: string[]; type: PaginationType; variable: string }

function fieldsOf(type: GraphQLNamedType) {
  return isObjectType(type) || isInterfaceType(type) ? type.getFields() : {}
}

export function paginatedField(field: GraphQLField<unknown, unknown>): PaginatedField | null {
  const type = getNamedType(field.type)
  const fields = fieldsOf(type)
  const args = field.args.map((arg) => arg.name)

  if (fields.edges && fields.pageInfo && args.includes('first') && args.includes('after')) {
    return { type: 'CONNECTION', pageArgument: 'after', keyArgs: args.filter((arg) => arg !== 'after') }
  }
  if (fields.data && fields.paginatorInfo && args.includes('first') && args.includes('page')) {
    const simple = getNamedType(fields.paginatorInfo.type).name === 'SimplePaginatorInfo'
    return { type: simple ? 'SIMPLE' : 'PAGINATOR', pageArgument: 'page', keyArgs: args.filter((arg) => arg !== 'page') }
  }
  return null
}

// Every paginated field of the schema, by type and field name.
export function paginatedFields(schema: GraphQLSchema) {
  const result: Record<string, Record<string, PaginatedField>> = {}
  for (const type of Object.values(schema.getTypeMap())) {
    if (type.name.startsWith('__') || !isObjectType(type)) continue
    for (const field of Object.values(type.getFields())) {
      const paginated = paginatedField(field)
      if (paginated) (result[type.name] ??= {})[field.name] = paginated
    }
  }
  return result
}

/**
 * The paginated fields an operation selects whose page argument is one of its
 * variables: what `useConnection` advances with fetchMore. `path` is response keys.
 */
export function operationPagination(schema: GraphQLSchema, document: string): OperationPagination[] {
  const ast = parse(document)
  const fragments = new Map<string, FragmentDefinitionNode>()
  let operation: OperationDefinitionNode | undefined
  for (const definition of ast.definitions) {
    if (definition.kind === 'FragmentDefinition') fragments.set(definition.name.value, definition)
    else if (definition.kind === 'OperationDefinition') operation = definition
  }
  if (!operation) return []

  const root = schema.getRootType(operation.operation)
  const found: OperationPagination[] = []

  const visit = (selectionSet: SelectionSetNode, parent: GraphQLNamedType, path: string[], seen: Set<string>) => {
    for (const selection of selectionSet.selections) {
      if (selection.kind === 'InlineFragment') {
        const type = selection.typeCondition ? schema.getType(selection.typeCondition.name.value) : parent
        if (type) visit(selection.selectionSet, type, path, seen)
      } else if (selection.kind === 'FragmentSpread') {
        const fragment = fragments.get(selection.name.value)
        if (!fragment || seen.has(fragment.name.value)) continue
        const type = schema.getType(fragment.typeCondition.name.value)
        if (type) visit(fragment.selectionSet, type, path, new Set([...seen, fragment.name.value]))
      } else {
        visitField(selection, parent, path, seen)
      }
    }
  }

  const visitField = (node: FieldNode, parent: GraphQLNamedType, path: string[], seen: Set<string>) => {
    const field = fieldsOf(parent)[node.name.value]
    if (!field) return
    const fieldPath = [...path, node.alias?.value ?? node.name.value]

    const paginated = paginatedField(field)
    const pageArgument = paginated && node.arguments?.find((arg) => arg.name.value === paginated.pageArgument)
    if (paginated && pageArgument?.value.kind === 'Variable') {
      found.push({ path: fieldPath, type: paginated.type, variable: pageArgument.value.name.value })
    }
    if (node.selectionSet) visit(node.selectionSet, getNamedType(field.type), fieldPath, seen)
  }

  if (root) visit(operation.selectionSet, root, [], new Set())
  return found
}

const HEADER = '// Generated by vite/inertia-graphql from schema.graphql: do not edit.\n'

/** generated/type-policies.ts: a field policy for every field Lighthouse paginates. */
export function typePoliciesModule(schema: GraphQLSchema) {
  const fields = paginatedFields(schema)
  const lines: string[] = []
  let relay = false
  let pages = false

  for (const typeName of Object.keys(fields).sort()) {
    lines.push(`  ${typeName}: {`, '    fields: {')
    for (const [fieldName, field] of Object.entries(fields[typeName]).sort(([a], [b]) => a.localeCompare(b))) {
      const keyArgs = `[${field.keyArgs.map((arg) => `'${arg}'`).join(', ')}]`
      if (field.type === 'CONNECTION') {
        relay = true
        lines.push(`      ${fieldName}: relayStylePagination(${keyArgs}),`)
      } else {
        pages = true
        lines.push(`      ${fieldName}: pagePagination(${keyArgs}),`)
      }
    }
    lines.push('    },', '  },')
  }

  const imports = ["import type { TypePolicies } from '@apollo/client'"]
  if (relay) imports.push("import { relayStylePagination } from '@apollo/client/utilities'")
  // With its extension: test/javascript loads this module under Node, which resolves no other.
  if (pages) imports.push('', "import { pagePagination } from '../page-pagination.ts'")

  return [
    HEADER,
    ...imports,
    '',
    '// Pages of a list merge into one cache entry: the page argument (after, page) is left out',
    "// of keyArgs, the field's other arguments tell one list from another.",
    'export const typePolicies: TypePolicies = {',
    ...lines,
    '}',
    '',
  ].join('\n')
}

/** generated/pagination.ts: for each operation, the paginated fields its variables move. */
export function paginationModule(entries: Record<string, OperationPagination[]>) {
  const lines = Object.keys(entries)
    .sort()
    .filter((name) => entries[name].length > 0)
    .map((name) => {
      const items = entries[name].map(
        ({ path, type, variable }) => `{ path: [${path.map((key) => `'${key}'`).join(', ')}], type: '${type}', variable: '${variable}' }`,
      )
      return `  ${name}: [${items.join(', ')}],`
    })

  return [
    HEADER,
    "export type PaginationType = 'CONNECTION' | 'PAGINATOR' | 'SIMPLE'",
    '',
    'export type OperationPagination = { path: readonly string[]; type: PaginationType; variable: string }',
    '',
    '// The paginated fields each operation selects with a variable for the page (useConnection).',
    'export const pagination: Readonly<Record<string, readonly OperationPagination[]>> = {',
    ...lines,
    '}',
    '',
  ].join('\n')
}
